"""Assemble the starship scene from its parts.

The scene is the one style too big for a single file, so it is kept as parts
under styles/starship/ and joined into styles/scenes/starship.js, which
tools/inline_styles.py then inlines like any other scene:

    geom.js           SHIPGEOM: the sweep primitive and mesh finishing
    ships/<id>.js     SHIPS.<id>: one file per ship, in ORDER
    render.js         SHIPGL: the WebGL renderer, both looks
    scene.js          SCENES.starship: canvases, layout, pose, caption, callouts

    python tools/build_starship.py          write styles/scenes/starship.js
    python tools/build_starship.py --check  exit 1 if it is stale

The dev harness (silhouette fitting against reference drawings, the viewer)
lives in dev/starship/, which is not in the repo: the reference drawings are
third-party.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "styles" / "starship"
OUT = ROOT / "styles" / "scenes" / "starship.js"
ORDER = ["galaxy", "constitution", "intrepid", "defiant"]
HEAD = "/* generated by tools/build_starship.py from styles/starship/, edit there */"


def build():
    parts = [SRC / "geom.js"] + [SRC / "ships" / f"{s}.js" for s in ORDER] + [SRC / "render.js", SRC / "scene.js"]
    missing = [str(p) for p in parts if not p.exists()]
    if missing:
        sys.exit("missing: " + ", ".join(missing))
    body = "\n\n".join(p.read_text(encoding="utf-8").strip("\n") for p in parts)
    return HEAD + "\n" + body + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("starship.js is " + ("current" if ok else "STALE"))
        sys.exit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
